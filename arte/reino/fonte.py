def _linhas(ch):
    ch = ch.upper() if ch not in ('x',) else ch
    if ch in _ACENTO:
        base, ac = _ACENTO[ch]
        return _G[base].split('/'), (ac.split('/') if ac else None), (ch == 'Ç')
    return _G.get(ch, _G['?']).split('/'), None, False


def largura(s, esp=1):
    return sum(len(_linhas(c)[0][0]) + esp for c in s) - esp if s else 0


def _marcar(px, W, H, x, y, cor):
    if 0 <= x < W and 0 <= y < H: px[x, y] = cor


def texto(img, x, y, s, cor=(255, 246, 224), contorno=None, sombra=None, esp=1, centro=False, direita=False):
    """Desenha s com o topo das maiusculas em y. contorno = cor do contorno de 1 px; sombra = cor da sombra 1 px abaixo."""
    w = largura(s, esp)
    if centro: x -= w // 2
    if direita: x -= w
    pts = []
    cx = x
    for c in s:
        ls, ac, ced = _linhas(c)
        for j, l in enumerate(ls):
            for i, v in enumerate(l):
                if v == '#': pts.append((cx + i, y + j))
        if ac:
            for j, l in enumerate(ac):
                for i, v in enumerate(l):
                    if v == '#': pts.append((cx + i, y - 3 + j))
        if ced: pts += [(cx + 2, y + 7), (cx + 1, y + 8)]
        cx += len(ls[0]) + esp
    px = img.load(); W, H = img.size
    cor = tuple(cor) + (255,) if len(cor) == 3 else tuple(cor)
    if contorno:
        co = tuple(contorno) + (255,)
        for (a, b) in pts:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1, 2 if sombra else 1): _marcar(px, W, H, a + dx, b + dy, co)
    elif sombra:
        so = tuple(sombra) + (255,)
        for (a, b) in pts: _marcar(px, W, H, a, b + 1, so)
    for (a, b) in pts: _marcar(px, W, H, a, b, cor)
    return w
